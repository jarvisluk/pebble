export type ResolvedLang = 'zh-CN' | 'en';

function detectSystemLang(): ResolvedLang {
  try {
    const nav = typeof navigator !== 'undefined' ? navigator.language : '';
    const intlLoc = Intl?.DateTimeFormat?.().resolvedOptions?.().locale || '';
    const raw = nav || intlLoc || 'en';
    return /^zh\b/i.test(raw) ? 'zh-CN' : 'en';
  } catch {
    return 'en';
  }
}

