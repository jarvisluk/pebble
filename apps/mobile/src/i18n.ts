export type I18nKey = keyof typeof DICT['zh-CN'];

interface I18nContextValue {
  pref: LanguagePreference;
  lang: ResolvedLang;
  setPref: (next: LanguagePreference) => void;
  t: (key: I18nKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

let _activeLang: ResolvedLang = detectSystemLang();

export function tStatic(key: I18nKey, vars?: Record<string, string | number>): string {
  let s: string = DICT[_activeLang][key] ?? DICT['zh-CN'][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v ?? ''));
    }
  }
  return s;
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [pref, setPrefState] = useState<LanguagePreference>('system');

  useEffect(() => {
    loadLangPref()
      .then((saved) => setPrefState(saved))
      .catch(() => {});
  }, []);

  const setPref = useCallback((next: LanguagePreference) => {
    setPrefState(next);
    void saveLangPref(next).catch(() => {});
  }, []);

  const lang: ResolvedLang = useMemo(() => {
    const resolved: ResolvedLang = pref === 'zh-CN' || pref === 'en' ? pref : detectSystemLang();
    _activeLang = resolved;
    return resolved;
  }, [pref]);

  const t = useCallback(
    (key: I18nKey, vars?: Record<string, string | number>): string => {
      let s: string = DICT[lang][key] ?? DICT['zh-CN'][key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          s = s.replaceAll(`{${k}}`, String(v ?? ''));
        }
      }
      return s;
    },
    [lang]
  );

  const value = useMemo(() => ({ pref, lang, setPref, t }), [pref, lang, setPref, t]);

  return React.createElement(I18nContext.Provider, { value }, children);
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    const lang = detectSystemLang();
    return {
      pref: 'system',
      lang,
      setPref: () => {},
      t: (key, vars) => {
        let s: string = DICT[lang][key] ?? key;
        if (vars) {
          for (const [k, v] of Object.entries(vars)) {
            s = s.replaceAll(`{${k}}`, String(v ?? ''));
          }
        }
        return s;
      },
    };
  }
  return ctx;
}
